    private YYOptions options = new()
    {
        GMResourceInterface = typeof(IResourceBase),
        PropertyNameResolver = (prop) =>
        {
            var attr = prop.GetCustomAttribute<GameMakerProperty>();
            return attr?.PropertyName;
        },
        PolymorphicTypeResolver = (baseType, jsonObject) =>
        {
            var polyAttr = baseType.GetCustomAttribute<GameMakerPolymorphic>();

            if (polyAttr is null)
            {
                // not polymorphic ig
                return null;
            }

            // get the class
            string? classTag = jsonObject.Properties.Keys.FirstOrDefault(k => k.StartsWith("$"));
            if (classTag is null)
            {
                return null;
            }

            // strip the $
            string className = classTag.Substring(1);

            var derivedAttributes = baseType.GetCustomAttributes<GameMakerDerivedType>();
            var match = derivedAttributes.FirstOrDefault(attr => attr.TypeDiscriminator == className);
            return match?.DerivedType;
        },
        
        ShouldIgnoreProperty = (prop) => 
        {
            return prop.GetCustomAttribute<GameMakerIgnore>() is not null;
        },
            
        IgnoreWhenWritingNullResolver = (prop) =>
        {
            return prop.GetCustomAttribute<GameMakerIgnoreWhenWritingNull>() is not null;
        },
    };

