    public double Ratio { get; set; }
    public bool Enabled { get; set; }
    public MapperTestStatus Status { get; set; }
    public int? NullableInt { get; set; }
}

public class MapperCollectionsModel
{
    public List<string> Items { get; set; } = new();
    public HashSet<int> UniqueIds { get; set; } = new();
    public double[] Coordinates { get; set; } = Array.Empty<double>();
}

public class MapperDictionaryModel
{
    public Dictionary<string, int> Counts { get; set; } = new();
    public Dictionary<MapperTestStatus, string> StatusNames { get; set; } = new();
}

public class MapperIgnoreModel
{
    public string Kept { get; set; } = "kept";
    public string Ignored { get; set; } = "ignored";
    public int? NullIgnored { get; set; } = null;
    public int? NullKept { get; set; } = null;
    public string? NullableString { get; set; } = null;
}