    [Fact]
    public void HandlesPointArray()
    {
        string json = """
                      [
                        { "x": 10.0, "y": 20.0 },
                        { "x": 30.0, "y": 40.0 }
                      ]
                      """;
        YYParser parser = new YYParser(json);
        YYValue? root = parser.Parse();

        Point[]? points = YYMapper.Unmap<Point[]>(root!, options);

