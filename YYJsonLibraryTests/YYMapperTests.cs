        Assert.Equal(2, points.Length);
        Assert.Equal(10.0f, points[0].X);
        Assert.Equal(20.0f, points[0].Y);
        Assert.Equal(30.0f, points[1].X);
        Assert.Equal(40.0f, points[1].Y);
    }

    [Fact]
    public void MapValue_BasicTypes_And_Unmap_RoundTrip()
    {
        MapperBasicModel model = new()
        {
            Title = "Hello World",
            Count = 42,
            Ratio = 3.1415,
            Enabled = true,
            Status = MapperTestStatus.Active,
            NullableInt = 100
        };

        YYOptions emptyOptions = new();
        YYValue mapped = YYMapper.MapValue(model, emptyOptions);

        var obj = Assert.IsType<YYObject>(mapped);
        Assert.Equal("Hello World", obj["Title"].AsString());
        Assert.Equal(42, obj["Count"].AsNumber());
        Assert.Equal(3.1415, obj["Ratio"].AsNumber());
        Assert.True(obj["Enabled"].AsBool());
        Assert.Equal((double)MapperTestStatus.Active, obj["Status"].AsNumber());
        Assert.Equal(100, obj["NullableInt"].AsNumber());

        var unmapped = YYMapper.Unmap<MapperBasicModel>(mapped, emptyOptions);
        Assert.NotNull(unmapped);
        Assert.Equal(model.Title, unmapped.Title);
        Assert.Equal(model.Count, unmapped.Count);
        Assert.Equal(model.Ratio, unmapped.Ratio);
        Assert.Equal(model.Enabled, unmapped.Enabled);
        Assert.Equal(model.Status, unmapped.Status);
        Assert.Equal(model.NullableInt, unmapped.NullableInt);
    }

    [Fact]
    public void Unmap_Collections_List_HashSet_Array()
    {
        string json = """
                      {
                        "Items": ["one", "two", "three"],
                        "UniqueIds": [10, 20, 30, 20],
                        "Coordinates": [1.5, 2.5, 3.5]
                      }
                      """;

        YYValue root = new YYParser(json).Parse()!;
        MapperCollectionsModel? result = YYMapper.Unmap<MapperCollectionsModel>(root, new YYOptions());

        Assert.NotNull(result);
        Assert.Equal(new List<string> { "one", "two", "three" }, result.Items);
        Assert.Equal(new HashSet<int> { 10, 20, 30 }, result.UniqueIds);
        Assert.Equal(new[] { 1.5, 2.5, 3.5 }, result.Coordinates);
    }

    [Fact]
    public void Unmap_Dictionary_StringAndEnumKeys()
    {
        string json = """
                      {
                        "Counts": {
                          "apples": 5,
                          "oranges": 12
                        },
                        "StatusNames": {
                          "Active": "User is active",
                          "Pending": "User is pending"
                        }
                      }
                      """;

        YYValue root = new YYParser(json).Parse()!;
        MapperDictionaryModel? result = YYMapper.Unmap<MapperDictionaryModel>(root, new YYOptions());

        Assert.NotNull(result);
        Assert.Equal(5, result.Counts["apples"]);
        Assert.Equal(12, result.Counts["oranges"]);
        Assert.Equal("User is active", result.StatusNames[MapperTestStatus.Active]);
        Assert.Equal("User is pending", result.StatusNames[MapperTestStatus.Pending]);
    }

    [Fact]
    public void MapValue_RespectsShouldIgnoreProperty()
    {
        MapperIgnoreModel model = new();
        YYOptions customOptions = new()
        {
            ShouldIgnoreProperty = prop => prop.Name == "Ignored"
        };

        YYValue mapped = YYMapper.MapValue(model, customOptions);
        var obj = Assert.IsType<YYObject>(mapped);

        Assert.True(obj.Properties.ContainsKey("Kept"));
        Assert.False(obj.Properties.ContainsKey("Ignored"));
    }

    [Fact]
    public void MapValue_RespectsIgnoreWhenWritingNullResolver()
    {
        MapperIgnoreModel model = new();
        YYOptions customOptions = new()
        {
            IgnoreWhenWritingNullResolver = prop => prop.Name == "NullIgnored"
        };

        YYValue mapped = YYMapper.MapValue(model, customOptions);
        var obj = Assert.IsType<YYObject>(mapped);

        Assert.False(obj.Properties.ContainsKey("NullIgnored"));
        Assert.True(obj.Properties.ContainsKey("NullKept"));
        Assert.IsType<YYNull>(obj["NullKept"]);
        Assert.True(obj.Properties.ContainsKey("NullableString"));
        Assert.Equal("", obj["NullableString"].AsString());
    }

    [Fact]
    public void Unmap_ThrowsInvalidCastException_OnMismatchedTypes()
    {
        YYNumber num = new(42, false);
        Assert.Throws<InvalidCastException>(() => YYMapper.Unmap<MapperBasicModel>(num, new YYOptions()));
    }
