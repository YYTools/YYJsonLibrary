    [Fact]
    public void HandlesKeyOrdering()
    {
        var obj = new YYObject();
        obj.Properties["zebra"] = new YYNumber(1, false);
        obj.Properties["alpha"] = new YYNumber(2, false);
        obj.Properties["%Name"] = new YYString("MyName");
        obj.Properties["$GMSprite"] = new YYString("v1");
        obj.Properties["beta"] = new YYNumber(3, false);

        var writer = new YYWriter();
        string output = writer.Write(obj);

        int posDollar = output.IndexOf("\"$GMSprite\"");
        int posName = output.IndexOf("\"%Name\"");
        int posAlpha = output.IndexOf("\"alpha\"");
        int posBeta = output.IndexOf("\"beta\"");
        int posZebra = output.IndexOf("\"zebra\"");

        Assert.True(posDollar < posName);
        Assert.True(posName < posAlpha);
        Assert.True(posAlpha < posBeta);
        Assert.True(posBeta < posZebra);
    }

