    [Fact]
    public void HandlesPrimitivesAndEscaping()
    {
        var str = new YYString("hello \"world\" \\ newline:\n tab:\t");
        var writer = new YYWriter();
        Assert.Equal("\"hello \\\"world\\\" \\\\ newline:\\n tab:\\t\"", writer.Write(str));

        var numInt = new YYNumber(42, false);
        Assert.Equal("42", writer.Write(numInt));

        var numFloat = new YYNumber(42.5, true);
        Assert.Equal("42.5", writer.Write(numFloat));

        var bTrue = new YYBool(true);
        Assert.Equal("true", writer.Write(bTrue));

        var bFalse = new YYBool(false);
        Assert.Equal("false", writer.Write(bFalse));

        var n = new YYNull();
        Assert.Equal("null", writer.Write(n));
    }

